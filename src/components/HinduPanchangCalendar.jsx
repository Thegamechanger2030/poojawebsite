import { useState } from 'react';
import {
  CalendarDays,
  ChevronLeft,
  ChevronRight,
  Info,
  Phone
} from 'lucide-react';
import { getApproximateLunarDay, getApproximateObservances } from '../data/panchang';

const WEEKDAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MONTH_FORMAT = new Intl.DateTimeFormat('en-IN', { month: 'long', year: 'numeric' });
const SELECTED_DATE_FORMAT = new Intl.DateTimeFormat('en-IN', {
  weekday: 'long',
  day: 'numeric',
  month: 'long',
  year: 'numeric'
});

function sameDate(first, second) {
  return first.getFullYear() === second.getFullYear()
    && first.getMonth() === second.getMonth()
    && first.getDate() === second.getDate();
}

export default function HinduPanchangCalendar({ onNavigatePooja }) {
  const today = new Date();
  const [visibleMonth, setVisibleMonth] = useState(
    () => new Date(today.getFullYear(), today.getMonth(), 1)
  );
  const [selectedDate, setSelectedDate] = useState(
    () => new Date(today.getFullYear(), today.getMonth(), today.getDate())
  );

  const year = visibleMonth.getFullYear();
  const month = visibleMonth.getMonth();
  const firstWeekday = new Date(year, month, 1).getDay();
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  const calendarCells = [
    ...Array(firstWeekday).fill(null),
    ...Array.from({ length: daysInMonth }, (_, index) => index + 1)
  ];
  const selectedLunarDay = getApproximateLunarDay(selectedDate);
  const monthObservances = Array.from({ length: daysInMonth }, (_, index) => {
    const date = new Date(year, month, index + 1);
    return {
      date,
      observances: getApproximateObservances(date),
      lunarDay: getApproximateLunarDay(date)
    };
  }).filter(({ observances }) => observances.length > 0);

  const changeMonth = (offset) => {
    setVisibleMonth(new Date(year, month + offset, 1));
  };

  return (
    <section id="panchang-section" className="py-12 sm:py-16 bg-[#FFF9F0]">
      <div className="max-w-7xl mx-auto px-4 sm:px-6 space-y-8">
        <header className="text-center max-w-3xl mx-auto space-y-3">
          <div className="inline-flex items-center gap-2 bg-orange-100 border border-amber-300 px-4 py-1.5 rounded-full text-xs font-bold text-[#A83200]">
            <CalendarDays className="w-4 h-4" />
            <span>Original calendar generated by this site</span>
          </div>
          <h2 className="text-3xl sm:text-5xl font-extrabold font-serif text-stone-900">
            Hindu Calendar
          </h2>
          <p className="text-stone-600 text-sm sm:text-base leading-relaxed">
            Browse dates and see a simple lunar-cycle estimate. Festival dates and muhurat
            are not published here until they have been checked by Pandit ji.
          </p>
        </header>

        <div className="max-w-6xl mx-auto grid grid-cols-1 lg:grid-cols-12 gap-5 items-start">
        <div className="lg:col-span-8 bg-white rounded-3xl border border-amber-300 shadow-xl overflow-hidden">
          <div className="bg-gradient-to-r from-[#A83200] via-[#D94E1F] to-[#8C2700] p-5 sm:p-6 text-white flex items-center justify-between gap-4">
            <button
              type="button"
              onClick={() => changeMonth(-1)}
              aria-label="Previous month"
              className="rounded-xl p-2 hover:bg-white/15 focus:outline-none focus:ring-2 focus:ring-amber-200"
            >
              <ChevronLeft className="w-5 h-5" />
            </button>
            <h3 className="text-xl sm:text-2xl font-serif font-bold text-amber-100" aria-live="polite">
              {MONTH_FORMAT.format(visibleMonth)}
            </h3>
            <button
              type="button"
              onClick={() => changeMonth(1)}
              aria-label="Next month"
              className="rounded-xl p-2 hover:bg-white/15 focus:outline-none focus:ring-2 focus:ring-amber-200"
            >
              <ChevronRight className="w-5 h-5" />
            </button>
          </div>

          <div className="p-3 sm:p-6 bg-gradient-to-b from-[#fffdf8] to-orange-50/50">
            <div className="grid grid-cols-7 mb-2">
              {WEEKDAYS.map((weekday) => (
                <div key={weekday} className="text-center text-xs font-bold text-stone-500 py-2">
                  {weekday}
                </div>
              ))}
            </div>
            <div className="grid grid-cols-7 gap-1.5 sm:gap-2" role="grid" aria-label={MONTH_FORMAT.format(visibleMonth)}>
              {calendarCells.map((day, index) => {
                if (!day) {
                  return <div key={`empty-${index}`} aria-hidden="true" />;
                }

                const date = new Date(year, month, day);
                const lunarDay = getApproximateLunarDay(date);
                const observances = getApproximateObservances(date);
                const isToday = sameDate(date, today);
                const isSelected = sameDate(date, selectedDate);
                const isAuspiciousDate = observances.length > 0;

                return (
                  <button
                    key={day}
                    type="button"
                    role="gridcell"
                    aria-pressed={isSelected}
                    aria-label={`${day}, ${lunarDay.paksha}, ${lunarDay.tithi}${isToday ? ', today' : ''}`}
                    onClick={() => setSelectedDate(date)}
                    className={`min-h-[4.5rem] sm:min-h-24 rounded-xl border p-1.5 sm:p-2 text-left transition ${
                      isSelected
                        ? 'bg-orange-100 border-[#D94E1F] ring-2 ring-[#D94E1F]/30'
                        : isAuspiciousDate
                          ? 'bg-amber-50 border-amber-300 hover:bg-amber-100'
                          : 'bg-white border-amber-100 hover:border-amber-400 hover:bg-orange-50'
                    }`}
                  >
                    <span className="flex items-center justify-between gap-1">
                      <span className={`text-sm font-bold ${isToday ? 'text-[#D94E1F]' : 'text-stone-800'}`}>
                        {day}{isToday ? ' ·' : ''}
                      </span>
                      {isAuspiciousDate && (
                        <span
                          aria-hidden="true"
                          className="flex h-5 w-5 items-center justify-center rounded-full border border-amber-500 bg-amber-100 text-[9px] font-black leading-none text-[#A83200]"
                        >
                          श्री
                        </span>
                      )}
                    </span>
                    <span className="mt-1 block text-[9px] sm:text-[11px] leading-tight text-stone-500">
                      {lunarDay.tithi}
                    </span>
                    {isAuspiciousDate && (
                      <span className="mt-1 block text-[8px] sm:text-[9px] leading-tight font-bold text-[#A83200]">
                        {observances[0].replace(' (estimate)', '')}
                      </span>
                    )}
                  </button>
                );
              })}
            </div>
          </div>

          <div className="border-t border-amber-100 bg-orange-50/70 p-5 sm:p-6 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
            <div>
              <p className="text-xs font-bold uppercase tracking-wide text-amber-800">Selected date</p>
              <p className="mt-1 font-semibold text-stone-900">
                {SELECTED_DATE_FORMAT.format(selectedDate)}
              </p>
              <p className="mt-1 text-sm text-stone-600">
                {selectedLunarDay.paksha} · Approx. {selectedLunarDay.tithi}
              </p>
            </div>
            <a
              href="tel:9410202087"
              className="inline-flex items-center justify-center gap-2 rounded-full bg-[#D94E1F] px-5 py-3 text-sm font-bold text-white shadow hover:bg-[#A83200]"
            >
              <Phone className="w-4 h-4" />
              Confirm with Pandit ji
            </a>
          </div>
        </div>

        <aside className="lg:col-span-4 rounded-3xl border border-amber-300 bg-white shadow-xl overflow-hidden">
          <div className="bg-gradient-to-r from-amber-100 to-orange-100 p-5 border-b border-amber-200">
            <div className="flex items-center gap-2 text-[#A83200]">
              <span
                aria-hidden="true"
                className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full border-2 border-amber-500 bg-amber-100 text-xs font-black text-[#A83200]"
              >
                श्री
              </span>
              <h3 className="font-serif text-lg font-bold">Is mahine ke vrat aur parv</h3>
            </div>
            <p className="mt-1 text-xs text-stone-600">{MONTH_FORMAT.format(visibleMonth)} · approximate dates</p>
          </div>
          <div className="max-h-[32rem] overflow-y-auto p-4 space-y-3">
            {monthObservances.length > 0 ? monthObservances.map(({ date, observances, lunarDay }) => (
              <button
                key={date.toISOString()}
                type="button"
                onClick={() => setSelectedDate(date)}
                className={`w-full rounded-2xl border p-3 text-left transition ${
                  sameDate(date, selectedDate)
                    ? 'border-[#D94E1F] bg-orange-50'
                    : 'border-amber-100 bg-[#fffdf9] hover:border-amber-300 hover:bg-amber-50'
                }`}
              >
                <span className="flex items-start justify-between gap-3">
                  <span>
                    <span className="block text-sm font-bold text-stone-900">
                      {observances[0].replace(' (estimate)', '')}
                    </span>
                    <span className="mt-1 block text-xs text-stone-500">
                      {SELECTED_DATE_FORMAT.format(date)}
                    </span>
                    <span className="mt-1 block text-[11px] text-amber-800">
                      {lunarDay.paksha} · {lunarDay.tithi} (estimate)
                    </span>
                  </span>
                  <span className="rounded-full bg-amber-100 px-2 py-1 text-[10px] font-bold text-amber-900">
                    Vrat
                  </span>
                </span>
              </button>
            )) : (
              <p className="rounded-2xl bg-orange-50 p-4 text-sm text-stone-600">
                Is month ke liye estimate mein koi special vrat date nahi mili.
              </p>
            )}
          </div>
          <div className="border-t border-amber-100 bg-orange-50/70 p-4">
            <a
              href="tel:9410202087"
              className="inline-flex w-full items-center justify-center gap-2 rounded-full bg-[#D94E1F] px-4 py-3 text-sm font-bold text-white hover:bg-[#A83200]"
            >
              <Phone className="w-4 h-4" />
              Vrat date Pandit ji se confirm karein
            </a>
          </div>
        </aside>
        </div>

        <div className="max-w-6xl mx-auto flex items-start gap-3 rounded-2xl border border-amber-300 bg-amber-50 p-4 text-xs sm:text-sm text-stone-700">
          <Info className="w-5 h-5 shrink-0 text-amber-700" />
          <p>
            Lunar labels are estimates based on an average lunar-cycle formula. They are
            not a traditional Panchang calculation, do not account for local sunrise, and
            are not guaranteed to be 70% accurate. Please call Pandit ji to confirm any
            vrat, festival, tithi, or muhurat before planning.
          </p>
        </div>

        {onNavigatePooja && (
          <div className="text-center">
            <button
              type="button"
              onClick={onNavigatePooja}
              className="text-sm font-semibold text-[#A83200] underline underline-offset-4 hover:text-[#D94E1F]"
            >
              View puja services
            </button>
          </div>
        )}
      </div>
    </section>
  );
}
